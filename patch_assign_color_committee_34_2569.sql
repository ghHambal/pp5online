  (t.profile_id IS NULL) AS ยังไม่มีบัญชี
FROM unmatched_words uw
JOIN public.teachers t
  ON t.full_name ILIKE '%' || uw.first_word || '%'
  OR (uw.second_word <> '' AND t.full_name ILIKE '%' || uw.second_word || '%')
ORDER BY input_name, possible_match;


