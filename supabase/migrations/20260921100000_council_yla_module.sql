drop policy if exists council_yla_events_authenticated_read on public.council_yla_events;
create policy council_yla_events_authenticated_read on public.council_yla_events
  for select to authenticated using (status <> 'cancelled');
drop policy if exists council_yla_events_staff_write on public.council_yla_events;
create policy council_yla_events_staff_write on public.council_yla_events
  for all to authenticated
  using (get_user_role() = any (array['admin', 'teacher']))
  with check (get_user_role() = any (array['admin', 'teacher']));

