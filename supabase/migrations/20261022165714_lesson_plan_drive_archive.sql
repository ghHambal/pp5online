-- Store a teaching date per classroom/session and keep an auditable link to
-- the weekly Google Drive PDF created for each course.

alter table public.lesson_plan_reflections
  add column if not exists lesson_date date;

comment on column public.lesson_plan_reflections.lesson_date is
  'Actual teaching date for this lesson plan, classroom, and week.';

create table if not exists public.lesson_plan_archives (
  id bigint generated by default as identity primary key,
  course_id integer not null references public.master_subjects(id) on delete cascade,
  teacher_id integer not null references public.teachers(id) on delete cascade,
  academic_year integer not null,
  semester integer not null check (semester in (1, 2)),
  week_no integer not null check (week_no between 1 and 60),
  status text not null default 'completed' check (status in ('processing', 'completed', 'failed')),
  drive_root_folder_id text,
  drive_week_folder_id text,
  drive_teacher_folder_id text,
  drive_file_id text,
  drive_url text,
  file_name text not null,
  checksum_sha256 text,
  plan_count integer not null default 0 check (plan_count >= 0),
  room_count integer not null default 0 check (room_count >= 0),
  file_size_bytes bigint check (file_size_bytes is null or file_size_bytes >= 0),
  replaced_file_id text,
  error_message text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (course_id, academic_year, semester, week_no)
);

create index if not exists lesson_plan_archives_teacher_term_idx
  on public.lesson_plan_archives (teacher_id, academic_year, semester, week_no);

alter table public.lesson_plan_archives enable row level security;

drop policy if exists lesson_plan_archives_teacher_read on public.lesson_plan_archives;
create policy lesson_plan_archives_teacher_read
  on public.lesson_plan_archives
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.master_subjects ms
      join public.teachers t on t.id = ms.teacher_id
      where ms.id = lesson_plan_archives.course_id
        and t.profile_id = (select auth.uid())
    )
  );

drop policy if exists lesson_plan_archives_admin_manage on public.lesson_plan_archives;
create policy lesson_plan_archives_admin_manage
  on public.lesson_plan_archives
  for all
  to authenticated
  using (
    exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid())
        and (p.role = 'admin' or p.is_also_admin is true)
    )
  )
  with check (
    exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid())
        and (p.role = 'admin' or p.is_also_admin is true)
    )
  );

grant select, insert, update, delete on public.lesson_plan_archives to authenticated;
grant usage, select on sequence public.lesson_plan_archives_id_seq to authenticated;

