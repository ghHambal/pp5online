-- Store Google Drive archive settings per teacher and term. A teacher's
-- personal folder must never be selected from a global system setting.

create table if not exists public.teacher_lesson_plan_drive_settings (
  id bigint generated by default as identity primary key,
  teacher_id integer not null references public.teachers(id) on delete cascade,
  academic_year integer not null,
  semester integer not null check (semester in (1, 2)),
  dept_code text,
  root_folder_id text not null check (root_folder_id ~ '^[A-Za-z0-9_-]{10,}$'),
  create_folders boolean not null default true,
  replace_mode text not null default 'replace' check (replace_mode in ('replace', 'version')),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (teacher_id, academic_year, semester)
);

create index if not exists teacher_lesson_plan_drive_settings_owner_idx
  on public.teacher_lesson_plan_drive_settings (teacher_id, academic_year, semester);

alter table public.teacher_lesson_plan_drive_settings enable row level security;

drop policy if exists teacher_lesson_plan_drive_settings_read_own on public.teacher_lesson_plan_drive_settings;
create policy teacher_lesson_plan_drive_settings_read_own
  on public.teacher_lesson_plan_drive_settings
  for select
  to authenticated
  using (
    exists (
      select 1
      from public.teachers t
      where t.id = teacher_lesson_plan_drive_settings.teacher_id
        and t.profile_id = (select auth.uid())
    )
  );

drop policy if exists teacher_lesson_plan_drive_settings_insert_own on public.teacher_lesson_plan_drive_settings;
create policy teacher_lesson_plan_drive_settings_insert_own
  on public.teacher_lesson_plan_drive_settings
  for insert
  to authenticated
  with check (
    exists (
      select 1
      from public.teachers t
      where t.id = teacher_lesson_plan_drive_settings.teacher_id
        and t.profile_id = (select auth.uid())
    )
  );

drop policy if exists teacher_lesson_plan_drive_settings_update_own on public.teacher_lesson_plan_drive_settings;
create policy teacher_lesson_plan_drive_settings_update_own
  on public.teacher_lesson_plan_drive_settings
  for update
  to authenticated
  using (
    exists (
      select 1
      from public.teachers t
      where t.id = teacher_lesson_plan_drive_settings.teacher_id
        and t.profile_id = (select auth.uid())
    )
  )
  with check (
    exists (
      select 1
      from public.teachers t
      where t.id = teacher_lesson_plan_drive_settings.teacher_id
        and t.profile_id = (select auth.uid())
    )
  );

drop policy if exists teacher_lesson_plan_drive_settings_admin_manage on public.teacher_lesson_plan_drive_settings;
create policy teacher_lesson_plan_drive_settings_admin_manage
  on public.teacher_lesson_plan_drive_settings
  for all
  to authenticated
  using (
    exists (
      select 1
      from public.profiles p
      where p.id = (select auth.uid())
        and (p.role = 'admin' or p.is_also_admin is true)
    )
  )
  with check (
    exists (
      select 1
      from public.profiles p
      where p.id = (select auth.uid())
        and (p.role = 'admin' or p.is_also_admin is true)
    )
  );

grant select, insert, update, delete on public.teacher_lesson_plan_drive_settings to authenticated;
grant usage, select on sequence public.teacher_lesson_plan_drive_settings_id_seq to authenticated;

-- The supplied folder is the requesting teacher's personal folder for 2569/2.
-- It is deliberately scoped to this teacher and is not a system-wide default.
insert into public.teacher_lesson_plan_drive_settings
  (teacher_id, academic_year, semester, dept_code, root_folder_id, create_folders, replace_mode, enabled, updated_at)
select 85, 2569, 2, 'MATH', '1u9ZGSOBbaIImdOrBuL4crGTJnsCRPaoq', true, 'replace', true, now()
where exists (select 1 from public.teachers where id = 85)
on conflict (teacher_id, academic_year, semester) do update
set dept_code = excluded.dept_code,
    root_folder_id = excluded.root_folder_id,
    create_folders = excluded.create_folders,
    replace_mode = excluded.replace_mode,
    enabled = excluded.enabled,
    updated_at = excluded.updated_at;
