-- Student leave notice: a private, pre-approved discipline slip is reviewed by
-- the student's current homeroom advisor before attendance is updated.

create table if not exists public.student_leave_requests (
  id bigint generated by default as identity primary key,
  student_id integer not null references public.students(id) on delete cascade,
  leave_type text not null check (leave_type in ('excused', 'sick')),
  start_date date not null,
  end_date date not null,
  reason text,
  proof_path text,
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'expired')),
  teacher_comment text,
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  attendance_rows_count integer not null default 0,
  attendance_applied_at timestamptz,
  proof_delete_after timestamptz not null default (now() + interval '7 days'),
  proof_deleted_at timestamptz,
  created_at timestamptz not null default now(),
  constraint student_leave_request_dates check (end_date >= start_date)
);

create index if not exists student_leave_requests_student_created_idx
  on public.student_leave_requests (student_id, created_at desc);
create index if not exists student_leave_requests_status_dates_idx
  on public.student_leave_requests (status, start_date, end_date);
create index if not exists student_leave_requests_proof_cleanup_idx
  on public.student_leave_requests (proof_delete_after) where proof_path is not null;

alter table public.attendances
  add column if not exists leave_request_id bigint
  references public.student_leave_requests(id) on delete set null;

alter table public.student_leave_requests enable row level security;
revoke all on public.student_leave_requests from anon, authenticated;
grant select on public.student_leave_requests to authenticated;
grant insert (student_id, leave_type, start_date, end_date, reason, proof_path)
  on public.student_leave_requests to authenticated;

create or replace function public._can_review_student_leave(p_student_id integer)
returns boolean
language sql stable security definer
set search_path = ''
as $$
  select auth.uid() is not null and (
    exists (
      select 1 from public.profiles p
      where p.id = (select auth.uid())
        and (p.role = 'admin' or p.is_also_admin is true)
    )
    or exists (
      select 1
      from public.students s
      join public.homeroom_teachers h
        on h.main_room = case when h.category = 'ศาสนา' then s.religion_room else s.main_room end
      join public.teachers t on t.id = h.teacher_id
      join public.system_config ay on ay.key = 'academicYear' and ay.value = h.academic_year::text
      join public.system_config sem on sem.key = 'semester' and sem.value = h.semester::text
      where s.id = p_student_id and t.profile_id = (select auth.uid())
    )
  );
$$;
revoke all on function public._can_review_student_leave(integer) from public, anon;
grant execute on function public._can_review_student_leave(integer) to authenticated;

drop policy if exists student_leave_requests_read_self_or_advisor on public.student_leave_requests;
create policy student_leave_requests_read_self_or_advisor
  on public.student_leave_requests for select to authenticated
  using (
    exists (select 1 from public.students s where s.id = student_id and s.profile_id = (select auth.uid()))
    or public._can_review_student_leave(student_id)
  );

drop policy if exists student_leave_requests_student_insert on public.student_leave_requests;
create policy student_leave_requests_student_insert
  on public.student_leave_requests for insert to authenticated
  with check (
    status = 'pending' and reviewed_by is null and reviewed_at is null
    and attendance_rows_count = 0 and attendance_applied_at is null
    and proof_deleted_at is null
    and exists (
      select 1 from public.students s
      where s.id = student_id and s.profile_id = (select auth.uid())
    )
    and proof_path like (student_id::text || '/%')
  );

