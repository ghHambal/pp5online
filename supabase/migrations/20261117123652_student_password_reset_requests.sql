-- Password reset requests submitted by a student for themselves or a classmate.
create table if not exists public.student_password_reset_requests (
  id bigint generated by default as identity primary key,
  student_id integer not null constraint sprr_target_student_fkey
    references public.students(id) on delete cascade,
  requester_student_id integer constraint sprr_requester_student_fkey
    references public.students(id) on delete set null,
  requested_by_profile_id uuid references public.profiles(id) on delete set null,
  request_kind text not null check (request_kind in ('self', 'friend')),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint sprr_review_state check (
    (status = 'pending' and reviewed_by is null and reviewed_at is null)
    or (status <> 'pending' and reviewed_by is not null and reviewed_at is not null)
  ),
  constraint sprr_friend_request_has_requester check (
    request_kind <> 'friend' or requester_student_id is not null
  )
);

create index if not exists sprr_status_created_idx
  on public.student_password_reset_requests (status, created_at desc);
create index if not exists sprr_requester_created_idx
  on public.student_password_reset_requests (requester_student_id, created_at desc);
create unique index if not exists sprr_one_pending_per_student
  on public.student_password_reset_requests (student_id) where status = 'pending';

alter table public.students
  add column if not exists password_reset_notice_at timestamptz;

alter table public.student_password_reset_requests enable row level security;
revoke all on public.student_password_reset_requests from anon, authenticated;
grant select on public.student_password_reset_requests to authenticated;

drop policy if exists sprr_read_owner_requester_or_advisor on public.student_password_reset_requests;
create policy sprr_read_owner_requester_or_advisor
  on public.student_password_reset_requests for select to authenticated
  using (
    exists (select 1 from public.students s where s.id = student_id and s.profile_id = (select auth.uid()))
    or exists (select 1 from public.students s where s.id = requester_student_id and s.profile_id = (select auth.uid()))
    or private._can_review_student_leave(student_id)
  );

create or replace function public.submit_student_password_reset_request(
  p_student_code text,
  p_request_kind text default 'self'
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_target public.students%rowtype;
  v_requester_id integer;
begin
  if p_request_kind not in ('self', 'friend') or nullif(btrim(p_student_code), '') is null then
    raise exception 'ข้อมูลคำขอไม่ถูกต้อง' using errcode = '22023';
  end if;

  select * into v_target
  from public.students
  where student_code = btrim(p_student_code) and is_active = true
  limit 1;
  -- Do not disclose whether a student code exists to an unauthenticated caller.
  if not found then return true; end if;

  if p_request_kind = 'self' then
    if auth.uid() is null then
      v_requester_id := v_target.id;
    else
      select id into v_requester_id from public.students
      where profile_id = (select auth.uid()) and is_active = true limit 1;
      if v_requester_id is null or v_requester_id <> v_target.id then return true; end if;
    end if;
  else
    if auth.uid() is null then
      raise exception 'กรุณาเข้าสู่ระบบก่อนแจ้งแทนเพื่อน' using errcode = '42501';
    end if;
    select id into v_requester_id from public.students
    where profile_id = (select auth.uid()) and is_active = true limit 1;
    if v_requester_id is null or v_requester_id = v_target.id then return true; end if;
  end if;

  insert into public.student_password_reset_requests (
    student_id, requester_student_id, requested_by_profile_id, request_kind
  ) values (
    v_target.id, v_requester_id, (select auth.uid()), p_request_kind
  ) on conflict (student_id) where status = 'pending' do nothing;

  return true;
end;
$$;
revoke all on function public.submit_student_password_reset_request(text, text) from public;
grant execute on function public.submit_student_password_reset_request(text, text) to anon, authenticated;

create or replace function public.review_student_password_reset_request(
  p_request_id bigint,
  p_approve boolean
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_request public.student_password_reset_requests%rowtype;
  v_student public.students%rowtype;
  v_password text;
begin
  if auth.uid() is null or p_approve is null then
    raise exception 'ต้องเข้าสู่ระบบเพื่อดำเนินการ' using errcode = '42501';
  end if;

  select * into v_request
  from public.student_password_reset_requests
  where id = p_request_id
  for update;
  if not found then raise exception 'ไม่พบคำขอนี้' using errcode = 'P0002'; end if;
  if not private._can_review_student_leave(v_request.student_id) then
    raise exception 'ไม่มีสิทธิ์ตรวจคำขอของนักเรียนคนนี้' using errcode = '42501';
  end if;
  if v_request.status <> 'pending' then
    raise exception 'คำขอนี้ถูกตรวจไปแล้ว' using errcode = '55000';
  end if;

  select * into v_student from public.students where id = v_request.student_id for update;
  if not found or v_student.is_active is not true then
    raise exception 'ไม่พบบัญชีนักเรียนที่ใช้งานอยู่' using errcode = 'P0002';
  end if;

  if p_approve then
    v_password := v_student.student_code || '0';
    if length(v_password) < 6 then
      raise exception 'รหัสนักเรียนสั้นเกินไปสำหรับรหัสผ่านชั่วคราว กรุณาติดต่อแอดมิน' using errcode = '22023';
    end if;

    -- Use the existing authorized Auth-management RPC; never update auth.users from the client.
    perform public.admin_update_student_auth(v_student.id, null::text, v_password);
    update public.students set password_reset_notice_at = now() where id = v_student.id;
    update public.student_password_reset_requests
      set status = 'approved', reviewed_by = (select auth.uid()), reviewed_at = now()
      where id = v_request.id;

    return jsonb_build_object(
      'status', 'approved',
      'student_id', v_student.id,
      'student_name', v_student.full_name,
      'student_code', v_student.student_code,
      'temporary_password', v_password,
      'request_kind', v_request.request_kind
    );
  end if;

  update public.student_password_reset_requests
    set status = 'rejected', reviewed_by = (select auth.uid()), reviewed_at = now()
    where id = v_request.id;
  return jsonb_build_object('status', 'rejected', 'student_id', v_student.id, 'request_kind', v_request.request_kind);
end;
$$;
revoke all on function public.review_student_password_reset_request(bigint, boolean) from public, anon;
grant execute on function public.review_student_password_reset_request(bigint, boolean) to authenticated;
