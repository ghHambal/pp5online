create or replace function public.asr_prayer_roster()
returns jsonb language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare v_uid uuid:=auth.uid(); v_json jsonb;
begin
  if v_uid is null then raise exception 'authentication required' using errcode='42501'; end if;
  if not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key in ('color_scanner','dorm_scanner','dorm_monitor')) and not public.asr_prayer_is_admin() and not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='report_viewer') then
    raise exception 'no Asr prayer roster access' using errcode='42501';
  end if;
  with scopes as (
    select a.scope_type,a.scope_value,a.role_key from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key in ('color_scanner','dorm_scanner','dorm_monitor')
  ), eligible as (
    select s.id student_id,s.student_code,s.full_name,s.main_room,s.house_color,'commuter'::text round_key,'color'::text scope_type,btrim(coalesce(s.house_color,'')) scope_value
      from public.students s where s.is_active and s.gender='หญิง' and nullif(btrim(s.house_color),'') is not null and btrim(s.house_color)<>'#N/A'
      and not exists(select 1 from public.asr_prayer_dorm_roster r where r.student_id=s.id and r.is_active)
    union all
    select s.id,s.student_code,s.full_name,s.main_room,s.house_color,'dorm','dorm',d.name
      from public.students s join public.asr_prayer_dorm_roster r on r.student_id=s.id and r.is_active join public.asr_prayer_dorms d on d.id=r.dorm_id and d.is_active
      where s.is_active and s.gender='หญิง'
  )
  select coalesce(jsonb_agg(jsonb_build_object('student_id',e.student_id,'student_code',e.student_code,'full_name',e.full_name,'main_room',e.main_room,'house_color',e.house_color,'round',e.round_key,'scope_type',e.scope_type,'scope_value',e.scope_value,'scanned',c.id is not null,'recorded_at',c.recorded_at) order by e.scope_type,e.scope_value,e.main_room,e.student_code),'[]'::jsonb)
  into v_json from eligible e
  left join public.asr_prayer_checkins c on c.student_id=e.student_id and c.check_date=(now() at time zone 'Asia/Bangkok')::date
  where public.asr_prayer_is_admin()
     or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and ((a.role_key='color_scanner' and e.scope_type='color' and a.scope_value=e.scope_value) or (a.role_key in ('dorm_scanner','dorm_monitor') and e.scope_type='dorm' and a.scope_value=e.scope_value) or a.role_key='report_viewer'));
  return v_json;
end $$;
revoke all on function public.asr_prayer_roster() from public, anon;
grant execute on function public.asr_prayer_roster() to authenticated;

create or replace function public.asr_prayer_scan(p_student_code text)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_uid uuid:=auth.uid(); v_cfg public.asr_prayer_settings%rowtype; v_now time; v_day date; v_round text; v_scope_type text; v_scope_value text; v_student public.students%rowtype; v_checkin public.asr_prayer_checkins%rowtype;
begin
  if v_uid is null then raise exception 'authentication required' using errcode='42501'; end if;
  select * into v_cfg from public.asr_prayer_settings where id=1;
  v_now:=(now() at time zone 'Asia/Bangkok')::time; v_day:=(now() at time zone 'Asia/Bangkok')::date;
  if v_now>=v_cfg.commuter_scan_start and v_now<v_cfg.commuter_scan_end then v_round:='commuter'; v_scope_type:='color';
  elsif v_now>=v_cfg.dorm_scan_start and v_now<v_cfg.dorm_scan_end then v_round:='dorm'; v_scope_type:='dorm';
  else raise exception 'ขณะนี้อยู่นอกช่วงเวลาสแกนละหมาดอัซรี'; end if;
  select * into v_student from public.students s where s.student_code=btrim(p_student_code) and s.is_active and s.gender='หญิง';
  if not found then raise exception 'ไม่พบนักเรียนหญิงที่ยังมีสถานะใช้งาน'; end if;
  if v_round='commuter' then
    if nullif(btrim(v_student.house_color),'') is null or btrim(v_student.house_color)='#N/A' then raise exception 'นักเรียนยังไม่ได้กำหนดสี กรุณาติดต่อผู้ดูแล'; end if;
    v_scope_value:=btrim(v_student.house_color);
    if exists(select 1 from public.asr_prayer_dorm_roster r where r.student_id=v_student.id and r.is_active) then raise exception 'นักเรียนอยู่ในรอบหอพัก'; end if;
    if not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='color_scanner' and a.scope_type='color' and a.scope_value=v_scope_value) then raise exception 'ไม่มีสิทธิ์สแกนนักเรียนสีนี้'; end if;
  else
    select d.name into v_scope_value from public.asr_prayer_dorm_roster r join public.asr_prayer_dorms d on d.id=r.dorm_id and d.is_active where r.student_id=v_student.id and r.is_active;
    if v_scope_value is null then raise exception 'ไม่พบนักเรียนในทะเบียนหอพักรอบอัซรี'; end if;
    if not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='dorm_scanner' and a.scope_type='dorm' and a.scope_value=v_scope_value) then raise exception 'ไม่มีสิทธิ์สแกนนักเรียนหอนี้'; end if;
  end if;
  insert into public.asr_prayer_checkins(student_id,check_date,round_key,scope_type,scope_value,scanner_profile_id)
  values(v_student.id,v_day,v_round,v_scope_type,v_scope_value,v_uid)
  on conflict(student_id,check_date) do nothing returning * into v_checkin;
  if v_checkin.id is null then
    select * into v_checkin from public.asr_prayer_checkins where student_id=v_student.id and check_date=v_day;
    return jsonb_build_object('status','duplicate','student',jsonb_build_object('id',v_student.id,'student_code',v_student.student_code,'full_name',v_student.full_name,'main_room',v_student.main_room,'image_url',v_student.image_url),'round',v_checkin.round_key,'scope_value',v_checkin.scope_value,'recorded_at',v_checkin.recorded_at);
  end if;
  return jsonb_build_object('status','saved','student',jsonb_build_object('id',v_student.id,'student_code',v_student.student_code,'full_name',v_student.full_name,'main_room',v_student.main_room,'image_url',v_student.image_url),'round',v_round,'scope_value',v_scope_value,'recorded_at',v_checkin.recorded_at);
end $$;
revoke all on function public.asr_prayer_scan(text) from public, anon;
grant execute on function public.asr_prayer_scan(text) to authenticated;

create or replace function public.asr_prayer_dashboard(p_check_date date default null)
returns jsonb language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare v_uid uuid:=auth.uid(); v_date date:=coalesce(p_check_date,(now() at time zone 'Asia/Bangkok')::date); v_global boolean; v_result jsonb;
begin
  if v_uid is null then raise exception 'authentication required' using errcode='42501'; end if;
  v_global:=public.asr_prayer_is_admin() or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='report_viewer');
  if not v_global and not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key in ('color_scanner','dorm_scanner','dorm_monitor')) then raise exception 'not authorized to view Asr dashboard' using errcode='42501'; end if;
  with eligible as (
    select s.id student_id,s.student_code,s.full_name,s.main_room,s.house_color,'commuter'::text round_key,'color'::text scope_type,btrim(coalesce(s.house_color,'ยังไม่ระบุสี')) scope_value
    from public.students s where s.is_active and s.gender='หญิง' and not exists(select 1 from public.asr_prayer_dorm_roster r where r.student_id=s.id and r.is_active)
    union all
    select s.id,s.student_code,s.full_name,s.main_room,s.house_color,'dorm','dorm',d.name from public.students s join public.asr_prayer_dorm_roster r on r.student_id=s.id and r.is_active join public.asr_prayer_dorms d on d.id=r.dorm_id and d.is_active where s.is_active and s.gender='หญิง'
  ), visible as (
    select e.*,c.id checkin_id,c.recorded_at,c.scanner_profile_id from eligible e left join public.asr_prayer_checkins c on c.student_id=e.student_id and c.check_date=v_date
    where v_global or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and ((a.role_key='color_scanner' and e.round_key='commuter' and a.scope_value=e.scope_value) or (a.role_key in ('dorm_scanner','dorm_monitor') and e.round_key='dorm' and a.scope_value=e.scope_value)))
  ), groups as (
    select round_key,scope_type,scope_value,count(*) eligible_count,count(checkin_id) checked_count,
      jsonb_agg(jsonb_build_object('student_id',student_id,'student_code',student_code,'full_name',full_name,'main_room',main_room,'house_color',house_color,'scanned',checkin_id is not null,'recorded_at',recorded_at) order by main_room,student_code) students
    from visible group by round_key,scope_type,scope_value
  )
  select jsonb_build_object('date',v_date,'groups',coalesce((select jsonb_agg(jsonb_build_object('round',round_key,'scope_type',scope_type,'scope_value',scope_value,'eligible',eligible_count,'scanned',checked_count,'pending',eligible_count-checked_count,'percent',case when eligible_count=0 then 0 else round(100.0*checked_count/eligible_count,1) end,'students',students) order by round_key,scope_value) from groups),'[]'::jsonb)) into v_result;
  return v_result;
end $$;
revoke all on function public.asr_prayer_dashboard(date) from public, anon;
grant execute on function public.asr_prayer_dashboard(date) to authenticated;
