create or replace function public.asr_prayer_set_dorm_access(p_profile_id uuid,p_dorm_id bigint,p_role text,p_enabled boolean)
returns boolean language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_uid uuid:=auth.uid(); v_name text;
begin
  if v_uid is null or not public.asr_prayer_is_admin() then raise exception 'admin access required' using errcode='42501'; end if;
  if p_role not in ('dorm_scanner','dorm_monitor') or p_enabled is null then raise exception 'invalid dorm permission'; end if;
  select name into v_name from public.asr_prayer_dorms where id=p_dorm_id and is_active;
  if v_name is null or not exists(select 1 from public.profiles where id=p_profile_id) then raise exception 'ไม่พบหอพักหรือบัญชีผู้ใช้'; end if;
  if p_enabled then
    insert into public.asr_prayer_access(profile_id,role_key,scope_type,scope_value,granted_by_profile_id)
    values(p_profile_id,p_role,'dorm',v_name,v_uid) on conflict (profile_id,role_key,scope_type,scope_value) where is_active do update set updated_at=now(),granted_by_profile_id=excluded.granted_by_profile_id;
  else update public.asr_prayer_access set is_active=false,updated_at=now() where profile_id=p_profile_id and role_key=p_role and scope_type='dorm' and scope_value=v_name and is_active; end if;
  insert into public.asr_prayer_audit_logs(actor_profile_id,action,details) values(v_uid,'dorm_access_changed',jsonb_build_object('profile_id',p_profile_id,'dorm_id',p_dorm_id,'role',p_role,'enabled',p_enabled));
  return true;
end $$;
revoke all on function public.asr_prayer_set_dorm_access(uuid,bigint,text,boolean) from public, anon;
grant execute on function public.asr_prayer_set_dorm_access(uuid,bigint,text,boolean) to authenticated;

create or replace function public.asr_prayer_set_report_viewers(p_profile_ids uuid[])
returns integer language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_uid uuid:=auth.uid(); v_ids uuid[]; v_count integer;
begin
  if v_uid is null or not public.asr_prayer_is_admin() then raise exception 'admin access required' using errcode='42501'; end if;
  select coalesce(array_agg(distinct x),'{}'::uuid[]) into v_ids from unnest(coalesce(p_profile_ids,'{}'::uuid[])) x where x is not null;
  select count(*) into v_count from public.profiles p where p.id=any(v_ids);
  if v_count<>cardinality(v_ids) then raise exception 'พบผู้ใช้ที่ไม่อยู่ในระบบ'; end if;
  update public.asr_prayer_access set is_active=false,updated_at=now() where role_key='report_viewer' and is_active;
  insert into public.asr_prayer_access(profile_id,role_key,scope_type,scope_value,granted_by_profile_id) select x,'report_viewer','global','',v_uid from unnest(v_ids) x;
  insert into public.asr_prayer_audit_logs(actor_profile_id,action,details) values(v_uid,'report_viewers_replaced',jsonb_build_object('profiles',v_ids));
  return cardinality(v_ids);
end $$;
