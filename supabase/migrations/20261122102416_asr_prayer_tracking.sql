-- Separate Asr prayer check-ins and narrowly scoped staff/student permissions.
create table if not exists public.asr_prayer_settings (
  id smallint primary key default 1 check (id = 1),
  commuter_scan_start time not null default '16:10',
  commuter_scan_end time not null default '16:20',
  dorm_scan_start time not null default '16:20',
  dorm_scan_end time not null default '16:30',
  updated_by_profile_id uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now(),
  constraint asr_prayer_scan_windows_order check (
    commuter_scan_start < commuter_scan_end
    and dorm_scan_start < dorm_scan_end
    and commuter_scan_end <= dorm_scan_start
  )
);
insert into public.asr_prayer_settings (id) values (1) on conflict (id) do nothing;

create table if not exists public.asr_prayer_dorms (
  id bigint generated by default as identity primary key,
  name text not null unique,
  is_active boolean not null default true,
  created_by_profile_id uuid references public.profiles(id) on delete set null,
  updated_by_profile_id uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now(),
  constraint asr_prayer_dorm_name_nonempty check (length(btrim(name)) between 1 and 100)
);

create table if not exists public.asr_prayer_dorm_roster (
  student_id integer primary key references public.students(id) on delete cascade,
  dorm_id bigint not null references public.asr_prayer_dorms(id) on delete restrict,
  is_active boolean not null default true,
  assigned_by_profile_id uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now()
);
create index if not exists asr_prayer_dorm_roster_dorm_idx
  on public.asr_prayer_dorm_roster (dorm_id, student_id) where is_active;

create table if not exists public.asr_prayer_access (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  student_id integer references public.students(id) on delete set null,
  role_key text not null check (role_key in ('delegate','color_scanner','dorm_scanner','dorm_monitor','report_viewer')),
  scope_type text not null check (scope_type in ('global','color','dorm')),
  scope_value text not null default '',
  is_active boolean not null default true,
  granted_by_profile_id uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now(),
  constraint asr_prayer_access_scope_shape check (
    (role_key in ('delegate','report_viewer') and scope_type='global' and scope_value='')
    or (role_key='color_scanner' and scope_type='color' and length(btrim(scope_value)) > 0)
    or (role_key in ('dorm_scanner','dorm_monitor') and scope_type='dorm' and length(btrim(scope_value)) > 0)
  )
);
create unique index if not exists asr_prayer_access_active_unique
  on public.asr_prayer_access (profile_id, role_key, scope_type, scope_value) where is_active;
create index if not exists asr_prayer_access_scope_idx
  on public.asr_prayer_access (scope_type, scope_value, role_key) where is_active;

create table if not exists public.asr_prayer_checkins (
  id bigint generated by default as identity primary key,
  student_id integer not null references public.students(id) on delete restrict,
  check_date date not null,
  round_key text not null check (round_key in ('commuter','dorm')),
  scope_type text not null check (scope_type in ('color','dorm')),
  scope_value text not null,
  scanner_profile_id uuid not null references public.profiles(id) on delete restrict,
  recorded_at timestamptz not null default now(),
  constraint asr_prayer_checkin_scope_matches_round check (
    (round_key='commuter' and scope_type='color') or (round_key='dorm' and scope_type='dorm')
  ),
  constraint asr_prayer_checkin_one_per_day unique (student_id, check_date)
);
create index if not exists asr_prayer_checkins_date_scope_idx
  on public.asr_prayer_checkins (check_date, round_key, scope_value);
create index if not exists asr_prayer_checkins_scanner_date_idx
  on public.asr_prayer_checkins (scanner_profile_id, check_date desc);

create table if not exists public.asr_prayer_audit_logs (
  id bigint generated by default as identity primary key,
  actor_profile_id uuid references public.profiles(id) on delete set null,
  action text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists asr_prayer_audit_logs_created_idx
  on public.asr_prayer_audit_logs (created_at desc);

alter table public.asr_prayer_settings enable row level security;
alter table public.asr_prayer_dorms enable row level security;
alter table public.asr_prayer_dorm_roster enable row level security;
alter table public.asr_prayer_access enable row level security;
alter table public.asr_prayer_checkins enable row level security;
alter table public.asr_prayer_audit_logs enable row level security;
revoke all on public.asr_prayer_settings, public.asr_prayer_dorms, public.asr_prayer_dorm_roster,
  public.asr_prayer_access, public.asr_prayer_checkins, public.asr_prayer_audit_logs from anon, authenticated;
revoke all on sequence public.asr_prayer_dorms_id_seq, public.asr_prayer_checkins_id_seq,
  public.asr_prayer_audit_logs_id_seq from anon, authenticated;

create or replace function public.asr_prayer_is_admin()
returns boolean language sql stable security definer set search_path = pg_catalog, public as $$
  select auth.uid() is not null and exists (
    select 1 from public.profiles p where p.id=(select auth.uid()) and (p.role='admin' or p.is_also_admin is true)
  );
$$;
revoke all on function public.asr_prayer_is_admin() from public, anon;
grant execute on function public.asr_prayer_is_admin() to authenticated;

create or replace function public.asr_prayer_my_access()
returns jsonb language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare v_uid uuid := auth.uid(); v_admin boolean; v_rows jsonb;
begin
  if v_uid is null then raise exception 'authentication required' using errcode='42501'; end if;
  v_admin := public.asr_prayer_is_admin();
  select coalesce(jsonb_agg(jsonb_build_object('role',a.role_key,'scope_type',a.scope_type,'scope_value',a.scope_value,'student_id',a.student_id)), '[]'::jsonb)
    into v_rows from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active;
  return jsonb_build_object(
    'is_admin',v_admin,
    'can_manage',v_admin or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='delegate'),
    'can_view_all',v_admin or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='report_viewer'),
    'assignments',v_rows,
    'settings',(select to_jsonb(s) - 'id' - 'updated_by_profile_id' - 'updated_at' from public.asr_prayer_settings s where s.id=1)
  );
end $$;
revoke all on function public.asr_prayer_my_access() from public, anon;
grant execute on function public.asr_prayer_my_access() to authenticated;

