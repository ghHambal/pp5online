create or replace function public.asr_prayer_save_schedule(p_commuter_start text,p_commuter_end text,p_dorm_start text,p_dorm_end text)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_uid uuid := auth.uid(); v_cs time; v_ce time; v_ds time; v_de time;
begin
  if v_uid is null then raise exception 'authentication required' using errcode='42501'; end if;
  if not public.asr_prayer_is_admin() and not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='delegate') then raise exception 'not authorized to edit Asr schedule' using errcode='42501'; end if;
  begin v_cs:=p_commuter_start::time; v_ce:=p_commuter_end::time; v_ds:=p_dorm_start::time; v_de:=p_dorm_end::time; exception when others then raise exception 'เวลาไม่ถูกต้อง กรุณาใช้รูปแบบ HH:MM'; end;
  if v_cs >= v_ce or v_ds >= v_de or v_ce > v_ds then raise exception 'ช่วงเวลาสแกนต้องเรียงต่อกันและห้ามทับซ้อน'; end if;
  update public.asr_prayer_settings set commuter_scan_start=v_cs,commuter_scan_end=v_ce,dorm_scan_start=v_ds,dorm_scan_end=v_de,updated_by_profile_id=v_uid,updated_at=now() where id=1;
  insert into public.asr_prayer_audit_logs(actor_profile_id,action,details) values(v_uid,'schedule_updated',jsonb_build_object('commuter_start',v_cs,'commuter_end',v_ce,'dorm_start',v_ds,'dorm_end',v_de));
  return (select to_jsonb(s)-'id' from public.asr_prayer_settings s where id=1);
end $$;
revoke all on function public.asr_prayer_save_schedule(text,text,text,text) from public, anon;
grant execute on function public.asr_prayer_save_schedule(text,text,text,text) to authenticated;

create or replace function public.asr_prayer_set_delegates(p_student_ids integer[])
returns integer language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_uid uuid:=auth.uid(); v_ids integer[]; v_count integer;
begin
  if v_uid is null or not public.asr_prayer_is_admin() then raise exception 'admin access required' using errcode='42501'; end if;
  select coalesce(array_agg(distinct x),'{}'::integer[]) into v_ids from unnest(coalesce(p_student_ids,'{}'::integer[])) x where x is not null;
  select count(*) into v_count from public.students s where s.id=any(v_ids) and s.is_active is true and s.profile_id is not null and left(coalesce(s.main_room,''),3)='ม.6';
  if v_count<>cardinality(v_ids) then raise exception 'เลือกได้เฉพาะนักเรียน ม.6 ที่มีบัญชีใช้งาน'; end if;
  update public.asr_prayer_access set is_active=false,updated_at=now() where role_key='delegate' and is_active;
  insert into public.asr_prayer_access(profile_id,student_id,role_key,scope_type,scope_value,granted_by_profile_id)
    select s.profile_id,s.id,'delegate','global','',v_uid from public.students s where s.id=any(v_ids);
  insert into public.asr_prayer_audit_logs(actor_profile_id,action,details) values(v_uid,'delegates_replaced',jsonb_build_object('student_ids',v_ids));
  return cardinality(v_ids);
end $$;
revoke all on function public.asr_prayer_set_delegates(integer[]) from public, anon;
grant execute on function public.asr_prayer_set_delegates(integer[]) to authenticated;

