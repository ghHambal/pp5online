-- Configurable Asr tracking window and color scanner duty rosters.
alter table public.asr_prayer_settings
  add column if not exists tracking_ends_on date;
alter table public.asr_prayer_settings
  add constraint asr_prayer_tracking_dates_order
  check (tracking_ends_on is null or tracking_ends_on >= tracking_started_on);

alter table public.asr_prayer_access
  drop constraint if exists asr_prayer_access_role_key_check;
alter table public.asr_prayer_access
  add constraint asr_prayer_access_role_key_check
  check (role_key in ('delegate','color_scanner','color_manager','dorm_scanner','dorm_monitor','report_viewer'));
alter table public.asr_prayer_access
  drop constraint if exists asr_prayer_access_scope_shape;
alter table public.asr_prayer_access
  add constraint asr_prayer_access_scope_shape check (
    (role_key in ('delegate','report_viewer') and scope_type='global' and scope_value='')
    or (role_key in ('color_scanner','color_manager') and scope_type='color' and length(btrim(scope_value)) > 0)
    or (role_key in ('dorm_scanner','dorm_monitor') and scope_type='dorm' and length(btrim(scope_value)) > 0)
  );

create table if not exists public.asr_prayer_color_duties (
  id bigint generated by default as identity primary key,
  duty_date date not null,
  house_color text not null,
  student_id integer not null references public.students(id) on delete cascade,
  assigned_by_profile_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint asr_prayer_color_duty_date_school_days check (extract(dow from duty_date)::integer between 0 and 4),
  constraint asr_prayer_color_duty_color_nonempty check (length(btrim(house_color)) between 1 and 80),
  constraint asr_prayer_color_duty_unique unique (duty_date, house_color, student_id)
);
create index if not exists asr_prayer_color_duties_date_color_idx
  on public.asr_prayer_color_duties (duty_date, house_color, student_id);
alter table public.asr_prayer_color_duties enable row level security;
revoke all on public.asr_prayer_color_duties from anon, authenticated;
revoke all on sequence public.asr_prayer_color_duties_id_seq from anon, authenticated;

create or replace function public.asr_prayer_my_access()
returns jsonb language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare v_uid uuid := auth.uid(); v_admin boolean; v_global_manager boolean; v_rows jsonb;
begin
  if v_uid is null then raise exception 'authentication required' using errcode='42501'; end if;
  v_admin := public.asr_prayer_is_admin();
  select coalesce(jsonb_agg(jsonb_build_object('role',a.role_key,'scope_type',a.scope_type,'scope_value',a.scope_value,'student_id',a.student_id)), '[]'::jsonb)
    into v_rows from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active;
  v_global_manager := v_admin or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='delegate');
  return jsonb_build_object(
    'is_admin',v_admin,
    'can_manage',v_global_manager or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='color_manager'),
    'can_manage_global',v_global_manager,
    'can_manage_schedule',v_global_manager or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='color_manager'),
    'can_view_all',v_admin or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='report_viewer'),
    'assignments',v_rows,
    'settings',(select to_jsonb(s) - 'id' - 'updated_by_profile_id' - 'updated_at' from public.asr_prayer_settings s where s.id=1)
  );
end $$;
revoke all on function public.asr_prayer_my_access() from public, anon;
grant execute on function public.asr_prayer_my_access() to authenticated;

create or replace function public.asr_prayer_save_tracking_window(p_start_date date, p_end_date date)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_uid uuid:=auth.uid(); v_result jsonb;
begin
  if v_uid is null or not public.asr_prayer_is_admin() then raise exception 'admin access required' using errcode='42501'; end if;
  if p_start_date is null or (p_end_date is not null and p_end_date<p_start_date) then raise exception 'วันสิ้นสุดต้องไม่อยู่ก่อนวันเริ่มต้น'; end if;
  update public.asr_prayer_settings set tracking_started_on=p_start_date,tracking_ends_on=p_end_date,updated_by_profile_id=v_uid,updated_at=now() where id=1;
  insert into public.asr_prayer_audit_logs(actor_profile_id,action,details) values(v_uid,'tracking_window_updated',jsonb_build_object('start_date',p_start_date,'end_date',p_end_date));
  select jsonb_build_object('start_date',tracking_started_on,'end_date',tracking_ends_on) into v_result from public.asr_prayer_settings where id=1;
  return v_result;
end $$;
revoke all on function public.asr_prayer_save_tracking_window(date,date) from public, anon;
grant execute on function public.asr_prayer_save_tracking_window(date,date) to authenticated;

create or replace function public.asr_prayer_set_color_managers(p_color text,p_student_ids integer[])
returns integer language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_uid uuid:=auth.uid(); v_color text:=nullif(btrim(p_color),''); v_ids integer[]; v_count integer;
begin
  if v_uid is null or not public.asr_prayer_is_admin() then raise exception 'admin access required' using errcode='42501'; end if;
  if v_color is null then raise exception 'กรุณาเลือกสี'; end if;
  select coalesce(array_agg(distinct x),'{}'::integer[]) into v_ids from unnest(coalesce(p_student_ids,'{}'::integer[])) x where x is not null;
  select count(*) into v_count from public.students s where s.id=any(v_ids) and s.is_active is true and s.gender='หญิง'
    and left(coalesce(s.main_room,''),3)='ม.6' and btrim(coalesce(s.house_color,''))=v_color
    and exists(select 1 from public.asr_prayer_access a where a.student_id=s.id and a.is_active and a.role_key='color_scanner' and a.scope_value=v_color);
  if v_count<>cardinality(v_ids) then raise exception 'หัวหน้าสีต้องเป็นผู้สแกนหญิง ม.6 ที่ได้รับมอบหมายในสีนั้นแล้ว'; end if;
  update public.asr_prayer_access set is_active=false,updated_at=now() where role_key='color_manager' and scope_type='color' and scope_value=v_color and is_active;
  insert into public.asr_prayer_access(profile_id,student_id,role_key,scope_type,scope_value,granted_by_profile_id)
    select s.profile_id,s.id,'color_manager','color',v_color,v_uid from public.students s where s.id=any(v_ids);
  insert into public.asr_prayer_audit_logs(actor_profile_id,action,details) values(v_uid,'color_managers_replaced',jsonb_build_object('color',v_color,'student_ids',v_ids));
  return cardinality(v_ids);
end $$;
revoke all on function public.asr_prayer_set_color_managers(text,integer[]) from public, anon;
grant execute on function public.asr_prayer_set_color_managers(text,integer[]) to authenticated;

create or replace function public.asr_prayer_color_schedule_data()
returns jsonb language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare v_uid uuid:=auth.uid(); v_global boolean; v_colors jsonb; v_scanners jsonb; v_duties jsonb; v_settings jsonb;
begin
  if v_uid is null then raise exception 'authentication required' using errcode='42501'; end if;
  v_global:=public.asr_prayer_is_admin() or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='delegate');
  if not v_global and not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='color_manager') then raise exception 'not authorized to manage color schedules' using errcode='42501'; end if;
  select to_jsonb(s)-'id'-'updated_by_profile_id'-'updated_at' into v_settings from public.asr_prayer_settings s where s.id=1;
  select coalesce(jsonb_agg(distinct a.scope_value order by a.scope_value),'[]'::jsonb) into v_colors
    from public.asr_prayer_access a where a.is_active and a.role_key='color_manager' and (v_global or a.profile_id=v_uid);
  if v_global then
    select coalesce(jsonb_agg(x.color order by x.color),'[]'::jsonb) into v_colors from (
      select distinct btrim(house_color) color from public.students where is_active and gender='หญิง' and nullif(btrim(house_color),'') is not null and btrim(house_color)<>'#N/A'
    ) x;
  end if;
  select coalesce(jsonb_agg(jsonb_build_object('student_id',s.id,'full_name',s.full_name,'student_code',s.student_code,'main_room',s.main_room,'house_color',s.house_color) order by s.house_color,s.main_room,s.full_name),'[]'::jsonb) into v_scanners
    from public.asr_prayer_access a join public.students s on s.id=a.student_id
    where a.is_active and a.role_key='color_scanner' and (v_global or exists(select 1 from public.asr_prayer_access m where m.profile_id=v_uid and m.student_id=a.student_id and m.is_active and m.role_key='color_manager' and m.scope_value=a.scope_value));
  select coalesce(jsonb_agg(jsonb_build_object('id',d.id,'duty_date',d.duty_date,'house_color',d.house_color,'student_id',d.student_id,'full_name',s.full_name,'student_code',s.student_code,'main_room',s.main_room) order by d.duty_date desc,d.house_color,s.full_name),'[]'::jsonb) into v_duties
    from (select * from public.asr_prayer_color_duties where duty_date >= (now() at time zone 'Asia/Bangkok')::date - 7
      and (v_global or exists(select 1 from public.asr_prayer_access m where m.profile_id=v_uid and m.is_active and m.role_key='color_manager' and m.scope_value=asr_prayer_color_duties.house_color))
      order by duty_date desc limit 300) d
    join public.students s on s.id=d.student_id where v_global or exists(select 1 from public.asr_prayer_access m where m.profile_id=v_uid and m.is_active and m.role_key='color_manager' and m.scope_value=d.house_color);
  return jsonb_build_object('settings',v_settings,'colors',v_colors,'scanners',v_scanners,'duties',v_duties,
    'color_managers',(select coalesce(jsonb_agg(jsonb_build_object('student_id',a.student_id,'scope_value',a.scope_value,'full_name',s.full_name,'student_code',s.student_code,'main_room',s.main_room) order by a.scope_value,s.full_name),'[]'::jsonb)
      from public.asr_prayer_access a left join public.students s on s.id=a.student_id where a.is_active and a.role_key='color_manager'
        and exists(select 1 from public.asr_prayer_access c where c.student_id=a.student_id and c.is_active and c.role_key='color_scanner' and c.scope_value=a.scope_value)
        and (v_global or a.profile_id=v_uid)));
end $$;
revoke all on function public.asr_prayer_color_schedule_data() from public, anon;
grant execute on function public.asr_prayer_color_schedule_data() to authenticated;

create or replace function public.asr_prayer_save_color_duty(p_duty_date date,p_color text,p_student_ids integer[])
returns jsonb language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_uid uuid:=auth.uid(); v_color text:=nullif(btrim(p_color),''); v_ids integer[]; v_count integer; v_settings public.asr_prayer_settings%rowtype;
begin
  if v_uid is null then raise exception 'authentication required' using errcode='42501'; end if;
  if not public.asr_prayer_is_admin() and not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='delegate')
    and not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='color_manager' and a.scope_value=btrim(coalesce(p_color,''))
      and exists(select 1 from public.asr_prayer_access c where c.student_id=a.student_id and c.is_active and c.role_key='color_scanner' and c.scope_value=a.scope_value))
  then raise exception 'ไม่มีสิทธิ์จัดเวรสีนี้' using errcode='42501'; end if;
  if p_duty_date is null or v_color is null then raise exception 'กรุณาเลือกวันที่และสี'; end if;
  select * into v_settings from public.asr_prayer_settings where id=1;
  if p_duty_date<v_settings.tracking_started_on or (v_settings.tracking_ends_on is not null and p_duty_date>v_settings.tracking_ends_on) then raise exception 'วันที่อยู่นอกช่วงเปิดใช้ระบบ'; end if;
  if extract(dow from p_duty_date)::integer not between 0 and 4 then raise exception 'จัดเวรได้เฉพาะวันอาทิตย์ถึงวันพฤหัสบดี'; end if;
  select coalesce(array_agg(distinct x),'{}'::integer[]) into v_ids from unnest(coalesce(p_student_ids,'{}'::integer[])) x where x is not null;
  select count(*) into v_count from public.students s where s.id=any(v_ids) and s.is_active and s.gender='หญิง'
    and left(coalesce(s.main_room,''),3)='ม.6' and btrim(coalesce(s.house_color,''))=v_color
    and exists(select 1 from public.asr_prayer_access a where a.student_id=s.id and a.is_active and a.role_key='color_scanner' and a.scope_value=v_color);
  if v_count<>cardinality(v_ids) then raise exception 'เลือกได้เฉพาะผู้สแกนที่ได้รับมอบหมายในสีนั้น'; end if;
  delete from public.asr_prayer_color_duties where duty_date=p_duty_date and house_color=v_color;
  insert into public.asr_prayer_color_duties(duty_date,house_color,student_id,assigned_by_profile_id)
    select p_duty_date,v_color,x,v_uid from unnest(v_ids) x;
  insert into public.asr_prayer_audit_logs(actor_profile_id,action,details) values(v_uid,'color_duty_saved',jsonb_build_object('duty_date',p_duty_date,'color',v_color,'student_ids',v_ids,'count',cardinality(v_ids)));
  return jsonb_build_object('duty_date',p_duty_date,'house_color',v_color,'assigned_count',cardinality(v_ids));
end $$;
revoke all on function public.asr_prayer_save_color_duty(date,text,integer[]) from public, anon;
grant execute on function public.asr_prayer_save_color_duty(date,text,integer[]) to authenticated;

create or replace function public.asr_prayer_scan(p_student_code text)
returns jsonb language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_uid uuid:=auth.uid(); v_cfg public.asr_prayer_settings%rowtype; v_now time; v_day date; v_round text; v_scope_type text; v_scope_value text; v_student public.students%rowtype; v_checkin public.asr_prayer_checkins%rowtype;
begin
  if v_uid is null then raise exception 'authentication required' using errcode='42501'; end if;
  select * into v_cfg from public.asr_prayer_settings where id=1;
  v_now:=(now() at time zone 'Asia/Bangkok')::time; v_day:=(now() at time zone 'Asia/Bangkok')::date;
  if v_day<v_cfg.tracking_started_on or (v_cfg.tracking_ends_on is not null and v_day>v_cfg.tracking_ends_on) then raise exception 'ระบบติดตามอัซรียังไม่เปิดใช้งานในวันนี้'; end if;
  if v_now>=v_cfg.commuter_scan_start and v_now<v_cfg.commuter_scan_end then v_round:='commuter'; v_scope_type:='color';
  elsif v_now>=v_cfg.dorm_scan_start and v_now<v_cfg.dorm_scan_end then v_round:='dorm'; v_scope_type:='dorm';
  else raise exception 'ขณะนี้อยู่นอกช่วงเวลาสแกนละหมาดอัซรี'; end if;
  select * into v_student from public.students s where s.student_code=btrim(p_student_code) and s.is_active and s.gender='หญิง';
  if not found then raise exception 'ไม่พบนักเรียนหญิงที่ยังมีสถานะใช้งาน'; end if;
  if v_round='commuter' then
    if nullif(btrim(v_student.house_color),'') is null or btrim(v_student.house_color)='#N/A' then raise exception 'นักเรียนยังไม่ได้กำหนดสี กรุณาติดต่อผู้ดูแล'; end if;
    v_scope_value:=btrim(v_student.house_color);
    if exists(select 1 from public.asr_prayer_dorm_roster r where r.student_id=v_student.id and r.is_active) then raise exception 'นักเรียนอยู่ในรอบหอพัก'; end if;
    if not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='color_scanner' and a.scope_type='color' and a.scope_value=v_scope_value) then raise exception 'ไม่มีสิทธิ์สแกนนักเรียนสีนี้'; end if;
  else
    select d.name into v_scope_value from public.asr_prayer_dorm_roster r join public.asr_prayer_dorms d on d.id=r.dorm_id and d.is_active where r.student_id=v_student.id and r.is_active;
    if v_scope_value is null then raise exception 'ไม่พบนักเรียนในทะเบียนหอพักรอบอัซรี'; end if;
    if not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='dorm_scanner' and a.scope_type='dorm' and a.scope_value=v_scope_value) then raise exception 'ไม่มีสิทธิ์สแกนนักเรียนหอนี้'; end if;
  end if;
  insert into public.asr_prayer_checkins(student_id,check_date,round_key,scope_type,scope_value,scanner_profile_id)
  values(v_student.id,v_day,v_round,v_scope_type,v_scope_value,v_uid)
  on conflict(student_id,check_date) do nothing returning * into v_checkin;
  if v_checkin.id is null then
    select * into v_checkin from public.asr_prayer_checkins where student_id=v_student.id and check_date=v_day;
    return jsonb_build_object('status','duplicate','student',jsonb_build_object('id',v_student.id,'student_code',v_student.student_code,'full_name',v_student.full_name,'main_room',v_student.main_room,'image_url',v_student.image_url),'round',v_checkin.round_key,'scope_value',v_checkin.scope_value,'recorded_at',v_checkin.recorded_at);
  end if;
  return jsonb_build_object('status','saved','student',jsonb_build_object('id',v_student.id,'student_code',v_student.student_code,'full_name',v_student.full_name,'main_room',v_student.main_room,'image_url',v_student.image_url),'round',v_round,'scope_value',v_scope_value,'recorded_at',v_checkin.recorded_at);
end $$;
revoke all on function public.asr_prayer_scan(text) from public, anon;
grant execute on function public.asr_prayer_scan(text) to authenticated;


-- Period dashboards also stop at the configured tracking end date.
create or replace function public.asr_prayer_dashboard_period(
  p_period_key text,
  p_anchor_date date default null,
  p_room text default null,
  p_color text default null,
  p_dorm text default null
)
returns jsonb
language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare
  v_uid uuid := auth.uid();
  v_today date := (now() at time zone 'Asia/Bangkok')::date;
  v_anchor date := coalesce(p_anchor_date, (now() at time zone 'Asia/Bangkok')::date);
  v_start date;
  v_end date;
  v_tracking_start date;
  v_tracking_end date;
  v_global boolean;
  v_result jsonb;
begin
  if v_uid is null then raise exception 'authentication required' using errcode='42501'; end if;
  if p_period_key not in ('day','week','month') then raise exception 'invalid Asr report period' using errcode='22023'; end if;
  if v_anchor > v_today then raise exception 'เลือกวันที่ในอนาคตไม่ได้' using errcode='22023'; end if;

  v_global := public.asr_prayer_is_admin() or exists (
    select 1 from public.asr_prayer_access a
    where a.profile_id=v_uid and a.is_active and a.role_key='report_viewer'
  );
  if not v_global and not exists (
    select 1 from public.asr_prayer_access a
    where a.profile_id=v_uid and a.is_active and a.role_key in ('color_scanner','dorm_scanner','dorm_monitor')
  ) then raise exception 'not authorized to view Asr dashboard' using errcode='42501'; end if;

  select tracking_started_on,tracking_ends_on into v_tracking_start,v_tracking_end from public.asr_prayer_settings where id=1;
  v_tracking_start := coalesce(v_tracking_start, date '2026-11-22');
  if p_period_key='day' then
    v_start := v_anchor;
    v_end := v_anchor;
  elsif p_period_key='week' then
    v_start := v_anchor - extract(dow from v_anchor)::integer;
    v_end := least(v_start + 4, v_anchor);
  else
    v_start := date_trunc('month', v_anchor)::date;
    v_end := v_anchor;
  end if;
  v_start := greatest(v_start, v_tracking_start);
  if v_tracking_end is not null then v_end := least(v_end,v_tracking_end); end if;

  with cohort as (
    select s.id student_id,s.student_code,s.full_name,s.main_room,s.house_color,s.image_url,
      'commuter'::text round_key,'color'::text scope_type,btrim(s.house_color) scope_value,null::text dorm_name
    from public.students s
    where s.is_active is true and s.gender='หญิง'
      and (left(btrim(coalesce(s.main_room,'')),3)<>'ม.6' or (
        strpos(split_part(btrim(coalesce(s.main_room,'')),' ',1),'/')>0
        and split_part(split_part(btrim(coalesce(s.main_room,'')),' ',1),'/',2)<>'0'
      ))
      and nullif(btrim(s.house_color),'') is not null and btrim(s.house_color)<>'#N/A'
      and not exists(select 1 from public.asr_prayer_dorm_roster r where r.student_id=s.id and r.is_active)
    union all
    select s.id,s.student_code,s.full_name,s.main_room,s.house_color,s.image_url,
      'dorm','dorm',d.name,d.name
    from public.students s
    join public.asr_prayer_dorm_roster r on r.student_id=s.id and r.is_active
    join public.asr_prayer_dorms d on d.id=r.dorm_id and d.is_active
    where s.is_active is true and s.gender='หญิง'
      and (left(btrim(coalesce(s.main_room,'')),3)<>'ม.6' or (
        strpos(split_part(btrim(coalesce(s.main_room,'')),' ',1),'/')>0
        and split_part(split_part(btrim(coalesce(s.main_room,'')),' ',1),'/',2)<>'0'
      ))
  ), scoped as (
    select c.* from cohort c
    where v_global or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and (
      (a.role_key='color_scanner' and c.round_key='commuter' and a.scope_value=c.scope_value)
      or (a.role_key in ('dorm_scanner','dorm_monitor') and c.round_key='dorm' and a.scope_value=c.scope_value)
    ))
  ), filtered as (
    select s.* from scoped s
    where (nullif(btrim(p_room),'') is null or s.main_room=btrim(p_room))
      and (nullif(btrim(p_color),'') is null or s.house_color=btrim(p_color))
      and (nullif(btrim(p_dorm),'') is null or s.dorm_name=btrim(p_dorm))
  ), calendar as (
    select g.day_value::date check_date
    from generate_series(v_start::timestamp, v_end::timestamp, interval '1 day') g(day_value)
    where p_period_key='day' or extract(dow from g.day_value)::integer between 0 and 4
  ), marks as (
    select f.*,cal.check_date,c.id checkin_id,
      (c.id is not null and c.round_key=f.round_key and c.scope_type=f.scope_type and c.scope_value=f.scope_value) matched,
      (c.id is not null and (c.round_key<>f.round_key or c.scope_type<>f.scope_type or c.scope_value<>f.scope_value)) mismatch,
      (c.id is null and (cal.check_date<v_today or (now() at time zone 'Asia/Bangkok')::time >= greatest(
        (select commuter_scan_end from public.asr_prayer_settings where id=1),
        (select dorm_scan_end from public.asr_prayer_settings where id=1)
      ))) finalized_missing
    from filtered f cross join calendar cal
    left join public.asr_prayer_checkins c on c.student_id=f.student_id and c.check_date=cal.check_date
  ), student_totals as (
    select student_id,student_code,full_name,main_room,house_color,image_url,round_key,scope_type,scope_value,dorm_name,
      count(*)::integer expected_days,
      count(*) filter(where matched)::integer scanned_days,
      count(*) filter(where finalized_missing)::integer missing_days,
      count(*) filter(where mismatch)::integer mismatch_days
    from marks group by student_id,student_code,full_name,main_room,house_color,image_url,round_key,scope_type,scope_value,dorm_name
  ), groups as (
    select round_key,scope_type,scope_value,
      sum(expected_days)::integer expected_count,
      sum(scanned_days)::integer scanned_count,
      (sum(expected_days)-sum(scanned_days))::integer pending_count,
      sum(mismatch_days)::integer mismatch_count,
      count(*)::integer student_count,
      count(*) filter(where scanned_days>0)::integer students_with_scan
    from student_totals group by round_key,scope_type,scope_value
  ), followup as (
    select * from student_totals where missing_days>0 or mismatch_days>0
    order by mismatch_days desc,missing_days desc,student_code limit 100
  )
  select jsonb_build_object(
    'period',p_period_key,'anchor_date',v_anchor,'start_date',v_start,'end_date',v_end,
    'tracking_started_on',v_tracking_start,
    'school_days',(select count(*) from calendar),
    'groups',coalesce((select jsonb_agg(jsonb_build_object(
      'round',round_key,'scope_type',scope_type,'scope_value',scope_value,
      'eligible',expected_count,'scanned',scanned_count,'pending',pending_count,
      'mismatches',mismatch_count,'student_count',student_count,'students_with_scan',students_with_scan,
      'percent',case when expected_count=0 then 0 else round(100.0*scanned_count/expected_count,1) end
    ) order by round_key,scope_value) from groups),'[]'::jsonb),
    'followup',coalesce((select jsonb_agg(jsonb_build_object(
      'student_id',student_id,'student_code',student_code,'full_name',full_name,'main_room',main_room,
      'house_color',house_color,'dorm_name',dorm_name,'image_url',image_url,'round',round_key,'scope_value',scope_value,
      'expected_days',expected_days,'scanned_days',scanned_days,'missing_days',missing_days,'mismatch_days',mismatch_days
    ) order by mismatch_days desc,missing_days desc,student_code) from followup),'[]'::jsonb),
    'followup_total',(select count(*) from student_totals where missing_days>0 or mismatch_days>0),
    'filter_options',jsonb_build_object(
      'rooms',coalesce((select jsonb_agg(x.value order by x.value) from (select distinct main_room value from scoped where nullif(main_room,'') is not null) x),'[]'::jsonb),
      'colors',coalesce((select jsonb_agg(x.value order by x.value) from (select distinct house_color value from scoped where nullif(house_color,'') is not null and house_color<>'#N/A') x),'[]'::jsonb),
      'dorms',coalesce((select jsonb_agg(x.value order by x.value) from (select distinct dorm_name value from scoped where dorm_name is not null) x),'[]'::jsonb)
    )
  ) into v_result;
  return v_result;
end $$;

create or replace function public.asr_prayer_dashboard_period_students(
  p_period_key text,
  p_anchor_date date,
  p_round_key text,
  p_scope_value text,
  p_room text default null,
  p_color text default null,
  p_dorm text default null
)
returns jsonb
language plpgsql stable security definer set search_path = pg_catalog, public as $$
declare
  v_uid uuid := auth.uid();
  v_today date := (now() at time zone 'Asia/Bangkok')::date;
  v_anchor date := coalesce(p_anchor_date, (now() at time zone 'Asia/Bangkok')::date);
  v_start date;
  v_end date;
  v_tracking_start date;
  v_tracking_end date;
  v_global boolean;
  v_students jsonb;
begin
  if v_uid is null then raise exception 'authentication required' using errcode='42501'; end if;
  if p_period_key not in ('day','week','month') or p_round_key not in ('commuter','dorm') then raise exception 'invalid Asr report scope' using errcode='22023'; end if;
  if v_anchor > v_today then raise exception 'เลือกวันที่ในอนาคตไม่ได้' using errcode='22023'; end if;
  v_global := public.asr_prayer_is_admin() or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key='report_viewer');
  if not v_global and not exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and a.role_key in ('color_scanner','dorm_scanner','dorm_monitor')) then raise exception 'not authorized to view Asr dashboard' using errcode='42501'; end if;
  select tracking_started_on,tracking_ends_on into v_tracking_start,v_tracking_end from public.asr_prayer_settings where id=1;
  v_tracking_start := coalesce(v_tracking_start, date '2026-11-22');
  if p_period_key='day' then v_start:=v_anchor;v_end:=v_anchor;
  elsif p_period_key='week' then v_start:=v_anchor-extract(dow from v_anchor)::integer;v_end:=least(v_start+4,v_anchor);
  else v_start:=date_trunc('month',v_anchor)::date;v_end:=v_anchor; end if;
  v_start:=greatest(v_start,v_tracking_start);
  if v_tracking_end is not null then v_end:=least(v_end,v_tracking_end); end if;
  with cohort as (
    select s.id student_id,s.student_code,s.full_name,s.main_room,s.house_color,s.image_url,
      'commuter'::text round_key,'color'::text scope_type,btrim(s.house_color) scope_value,null::text dorm_name
    from public.students s
    where p_round_key='commuter' and s.is_active is true and s.gender='หญิง'
      and (left(btrim(coalesce(s.main_room,'')),3)<>'ม.6' or (strpos(split_part(btrim(coalesce(s.main_room,'')),' ',1),'/')>0 and split_part(split_part(btrim(coalesce(s.main_room,'')),' ',1),'/',2)<>'0'))
      and nullif(btrim(s.house_color),'') is not null and btrim(s.house_color)<>'#N/A'
      and not exists(select 1 from public.asr_prayer_dorm_roster r where r.student_id=s.id and r.is_active)
    union all
    select s.id,s.student_code,s.full_name,s.main_room,s.house_color,s.image_url,'dorm','dorm',d.name,d.name
    from public.students s join public.asr_prayer_dorm_roster r on r.student_id=s.id and r.is_active join public.asr_prayer_dorms d on d.id=r.dorm_id and d.is_active
    where p_round_key='dorm' and s.is_active is true and s.gender='หญิง'
      and (left(btrim(coalesce(s.main_room,'')),3)<>'ม.6' or (strpos(split_part(btrim(coalesce(s.main_room,'')),' ',1),'/')>0 and split_part(split_part(btrim(coalesce(s.main_room,'')),' ',1),'/',2)<>'0'))
  ), scoped as (
    select c.* from cohort c where c.round_key=p_round_key and c.scope_value=p_scope_value
      and (nullif(btrim(p_room),'') is null or c.main_room=btrim(p_room))
      and (nullif(btrim(p_color),'') is null or c.house_color=btrim(p_color))
      and (nullif(btrim(p_dorm),'') is null or c.dorm_name=btrim(p_dorm))
      and (v_global or exists(select 1 from public.asr_prayer_access a where a.profile_id=v_uid and a.is_active and (
        (a.role_key='color_scanner' and c.round_key='commuter' and a.scope_value=c.scope_value)
        or (a.role_key in ('dorm_scanner','dorm_monitor') and c.round_key='dorm' and a.scope_value=c.scope_value)
      )))
  ), calendar as (
    select g.day_value::date check_date from generate_series(v_start::timestamp,v_end::timestamp,interval '1 day') g(day_value)
    where p_period_key='day' or extract(dow from g.day_value)::integer between 0 and 4
  ), marks as (
    select s.*,cal.check_date,c.id checkin_id,
      (c.id is not null and c.round_key=s.round_key and c.scope_type=s.scope_type and c.scope_value=s.scope_value) matched,
      (c.id is not null and (c.round_key<>s.round_key or c.scope_type<>s.scope_type or c.scope_value<>s.scope_value)) mismatch,
      (c.id is null and (cal.check_date<v_today or (now() at time zone 'Asia/Bangkok')::time >= greatest(
        (select commuter_scan_end from public.asr_prayer_settings where id=1),
        (select dorm_scan_end from public.asr_prayer_settings where id=1)
      ))) finalized_missing
    from scoped s cross join calendar cal left join public.asr_prayer_checkins c on c.student_id=s.student_id and c.check_date=cal.check_date
  ), totals as (
    select student_id,student_code,full_name,main_room,house_color,dorm_name,image_url,round_key,scope_value,
      count(*)::integer expected_days,count(*) filter(where matched)::integer scanned_days,
      count(*) filter(where finalized_missing)::integer missing_days,count(*) filter(where mismatch)::integer mismatch_days
    from marks group by student_id,student_code,full_name,main_room,house_color,dorm_name,image_url,round_key,scope_value
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'student_id',student_id,'student_code',student_code,'full_name',full_name,'main_room',main_room,
    'house_color',house_color,'dorm_name',dorm_name,'image_url',image_url,'round',round_key,'scope_value',scope_value,
    'expected_days',expected_days,'scanned_days',scanned_days,'missing_days',missing_days,'mismatch_days',mismatch_days
  ) order by mismatch_days desc,missing_days desc,full_name) ,'[]'::jsonb) into v_students from totals;
  return v_students;
end $$;
